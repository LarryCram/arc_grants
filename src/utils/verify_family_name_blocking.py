"""
src/utils/verify_family_name_blocking.py

Empirically measures whether the family_name_main "longest variant wins" collapse is
structurally blocking real ARC<->OAX matches from ever being scored by Splink -- the bug
documented in CLAUDE.md's "Next Priority" TODO (Erfani/Clarke cases) and confirmed a third
time via DP0345157_HansMuhlhaus (2026-08-25): ARC side has family_names=['muhlhaus'] (plain
ASCII, no diacritic to expand from); every one of his 4 OpenAlex fragments has
family_names containing BOTH 'muhlhaus' and 'muehlhaus', but family_name_main = max(...,
key=len) always picks 'muehlhaus' (9 chars beats 8) -- so the two sides' collapsed scalars
never match, even though a shared token genuinely exists in both sets.

This is a MEASUREMENT tool, not a claim. Run it before and after any fix to
family_name_main computation or Splink blocking rules -- the numbers here are the only
honest evidence that a fix actually changed anything, per the explicit 2026-08-25 direction:
"Write yourself a code to make sure that you have actually done what you say you have done."

Two checks:
1. Static audit -- every known call site that collapses a family-name SET to one scalar via
   longest-string-wins (max_by_len() or the equivalent inline max(..., key=len)), and
   whether it feeds a live Splink blocking rule (high stakes: silently makes a pair
   unreachable) or something else.
2. Empirical check -- for every ARC person with a ground-truth confirmed OAX match (resolved
   via 'orcid' in arc_oax_resolved.parquet -- the one bucket where the match is independently
   verified via an exact ORCID match, not just Splink's own scoring), does the ARC-side
   family_name_main STRING-EQUAL the OAX-side family_name_main? A mismatch here is proof
   that pair would never even be generated by block_on("family_name_main", "first_initial")
   -- it can only have been resolved via the ORCID force-add path, meaning if that person had
   no ORCID recorded, they would be structurally invisible to Splink regardless of how much
   real OpenAlex content they have.

CLI: .venv/bin/python -m src.utils.verify_family_name_blocking
"""
